/**
 * Returns the payout amount for a given global rank (1-150)
 */
export function getLeaderboardPayout(rank: number): number {
  if (rank >= 1 && rank <= 150) {
    return TOP_150_LEADERBOARD_REWARDS[rank] || 0;
  }
  return 0;
}

/**
 * Formats a payout number with commas or short abbreviations
 */
export function formatPayout(amount: number): string {
  return amount.toLocaleString();
}

export function formatCompactPayout(amount: number): string {
  if (amount >= 1000000000) return `${(amount / 1000000000).toFixed(amount % 1000000000 === 0 ? 0 : 1)}B`;
  if (amount >= 1000000) return `${(amount / 1000000).toFixed(amount % 1000000 === 0 ? 0 : 1)}M`;
  if (amount >= 1000) return `${(amount / 1000).toFixed(amount % 1000 === 0 ? 0 : 1)}K`;
  return amount.toString();
}

